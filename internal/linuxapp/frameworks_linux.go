func linuxProjectTemplateNames() []string {
	names := projectTemplateNames()
	seen := make(map[string]struct{}, len(names))
	for _, name := range names {
		seen[name] = struct{}{}
	}
	for _, name := range linuxFrameworkNames() {
		if _, ok := seen[name]; !ok {
			names = append(names, name)
			seen[name] = struct{}{}
		}
	}
	return names
}

func linuxFrameworkNames() []string {
	names := make([]string, 0, len(linuxFrameworkRecipes))
	for _, recipe := range linuxFrameworkRecipes {
		names = append(names, recipe.Name)
	}
	return names
}

func linuxFrameworkByName(name string) (linuxFrameworkRecipe, bool) {
	recipe, ok := linuxFrameworkByNameMap[name]
	return recipe, ok
}

func createLinuxFrameworkProject(root, name string, recipe linuxFrameworkRecipe, log func(string)) (string, error) {
	name = strings.TrimSpace(name)
	if !projectNamePattern.MatchString(name) {
		return "", fmt.Errorf("use 1–48 letters, numbers, underscores, or hyphens; the first character must be a letter or number")
	}
	name = strings.ToLower(name)
	if log == nil {
		log = func(string) {}
	}
	for _, required := range recipe.Required {
		if _, err := exec.LookPath(required); err != nil {
			return "", fmt.Errorf("%s is required but not found on PATH. Install it with your Linux distribution package manager and try again", required)
		}
	}
	if err := os.MkdirAll(root, 0o755); err != nil {
		return "", fmt.Errorf("create projects directory: %w", err)
	}
	rootAbs, err := filepath.Abs(root)
	if err != nil {
		return "", err
	}
	target := filepath.Join(rootAbs, name)
	if err := os.Mkdir(target, 0o755); err != nil {
		if os.IsExist(err) {
			return "", fmt.Errorf("a project named %q already exists", name)
		}
		return "", fmt.Errorf("create project directory: %w", err)
	}
	log("Preparing " + recipe.Name + " in " + target)
	// Keep the generation log outside the target while upstream generators run.
	// Some CLIs require that a freshly-created project directory is completely empty.
	logFile, err := os.CreateTemp(rootAbs, ".goampp-framework-*.log")
	if err != nil {
		return target, fmt.Errorf("create temporary project log: %w", err)
	}
	tempLogPath := logFile.Name()
	defer func() {
		_ = logFile.Sync()
		_ = logFile.Close()
		logPath := filepath.Join(target, ".goampp-run.log")
		if err := os.Rename(tempLogPath, logPath); err != nil {
			_ = os.Remove(tempLogPath)
		}
	}()
	logOutput := &linuxFrameworkLogWriter{file: logFile, onLine: log}
	if recipe.DownloadURL != "" {
		log("Downloading framework template for " + recipe.Name)
		if err := downloadLinuxFrameworkZip(recipe.DownloadURL, target, recipe.StripTop, log); err != nil {
			_, _ = fmt.Fprintf(logFile, "\n[GoAMPP] download failed: %v\n", err)
			return target, err
		}
	}
	for _, step := range recipe.Steps {
		if len(step.Args) == 0 { continue }
		args := make([]string, len(step.Args))
		for i, arg := range step.Args {
			args[i] = strings.ReplaceAll(arg, "{{name}}", name)
		}
		log(fmt.Sprintf("%s: %s", step.Title, strings.Join(args, " ")))
		ctx, cancel := context.WithTimeout(context.Background(), 20*time.Minute)
		cmd := exec.CommandContext(ctx, args[0], args[1:]...)
		cmd.Dir = target
		cmd.Env = environmentWith("GOAMPP_PROJECT_NAME", name)
		cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
		cmd.Cancel = func() error {
			if cmd.Process == nil {
				return nil
			}
			return terminateProcessGroup(cmd.Process.Pid, 500*time.Millisecond)
		}
		cmd.WaitDelay = time.Second
		cmd.Stdout = logOutput
		cmd.Stderr = logOutput
		err := cmd.Run()
		cancel()
		logOutput.Flush()
		if err != nil {
			_, _ = fmt.Fprintf(logFile, "\n[GoAMPP] step failed (%s): %v\n", step.Title, err)
			return target, fmt.Errorf("%s failed: %w. Partial files were kept; inspect the project Logs", step.Title, err)
		}
	}
	for rel, body := range recipe.Files {
		if !validTemplatePath(rel) {
			return target, fmt.Errorf("invalid framework template path %q", rel)
		}
		out := filepath.Join(target, filepath.FromSlash(rel))
		if err := atomicWriteLinuxFile(out, []byte(strings.ReplaceAll(body, "{{name}}", name)), 0o644); err != nil {
			return target, fmt.Errorf("write %s: %w", rel, err)
		}
		log("Created " + rel)
	}
	if recipe.Name == "NestJS" {
		if err := pinNestToLoopback(target); err != nil {
			_, _ = fmt.Fprintf(logFile, "\n[GoAMPP] loopback binding setup failed: %v\n", err)
			return target, err
		}
	}
	if err := atomicWriteLinuxFile(filepath.Join(target, ".goampp-framework"), []byte(recipe.Name+"\n"), 0o600); err != nil {
		return target, fmt.Errorf("save GoAMPP framework metadata: %w", err)
	}
	_ = logFile.Sync()
	log("Finished creating " + recipe.Name + " project at " + target)
	return target, nil
}

type linuxFrameworkLogWriter struct {
	mu      sync.Mutex
	file    *os.File
	onLine  func(string)
	pending string
}

func (w *linuxFrameworkLogWriter) Write(data []byte) (int, error) {
	w.mu.Lock()
	if _, err := w.file.Write(data); err != nil {
		w.mu.Unlock()
		return 0, err
	}
	all := w.pending + string(data)
	lines := strings.Split(all, "\n")
	w.pending = lines[len(lines)-1]
	complete := append([]string(nil), lines[:len(lines)-1]...)
	w.mu.Unlock()
	for _, line := range complete {
		line = strings.TrimSpace(line)
		if line != "" && w.onLine != nil { w.onLine(line) }
	}
	return len(data), nil
}

func (w *linuxFrameworkLogWriter) Flush() {
	w.mu.Lock()
	line := strings.TrimSpace(w.pending)
	w.pending = ""
	w.mu.Unlock()
	if line != "" && w.onLine != nil { w.onLine(line) }
}

func pinNestToLoopback(root string) error {
	path := filepath.Join(root, "src", "main.ts")
	data, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("pin NestJS to localhost: read src/main.ts: %w", err)
	}
	lines := strings.Split(string(data), "\n")
	changed := false
	for i, line := range lines {
		if strings.Contains(line, "await app.listen(") {
			indent := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
			lines[i] = indent + "await app.listen(Number(process.env.PORT ?? process.env.GOAMPP_PORT ?? 3000), '127.0.0.1');"
			changed = true
		}
	}
	if !changed {
		return fmt.Errorf("pin NestJS to localhost: could not locate the expected await app.listen(...) in src/main.ts; the project was not registered as runnable")
	}
	return atomicWriteLinuxFile(path, []byte(strings.Join(lines, "\n")), 0o644)
}

func downloadLinuxFrameworkZip(rawURL, root, stripTop string, log func(string)) error {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, rawURL, nil)
	if err != nil { return err }
	client := &http.Client{Timeout: 5*time.Minute}
	response, err := client.Do(req)
	if err != nil { return fmt.Errorf("download framework archive: %w", err) }
	defer response.Body.Close()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		return fmt.Errorf("download framework archive: server returned %s", response.Status)
	}
	tmp, err := os.CreateTemp(root, ".goampp-framework-*.zip")
	if err != nil { return err }
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	const maxArchiveSize = int64(512 * 1024 * 1024)
	n, err := io.Copy(tmp, io.LimitReader(response.Body, maxArchiveSize+1))
	if closeErr := tmp.Close(); err == nil { err = closeErr }
	if err != nil { return fmt.Errorf("download framework archive: %w", err) }
	if n > maxArchiveSize { return fmt.Errorf("framework archive exceeds the 512 MiB safety limit") }
	archive, err := zip.OpenReader(tmpName)
	if err != nil { return fmt.Errorf("invalid framework ZIP archive: %w", err) }
	defer archive.Close()
	extracted := 0
	var totalUncompressed int64
	const maxEntryUncompressed = int64(128 * 1024 * 1024)
	const maxTotalUncompressed = int64(1024 * 1024 * 1024)
	for _, file := range archive.File {
		entry := filepath.Clean(filepath.FromSlash(file.Name))
		if filepath.IsAbs(entry) || entry == ".." || strings.HasPrefix(entry, ".."+string(os.PathSeparator)) {
			return fmt.Errorf("archive contains an unsafe path: %q", file.Name)
		}
		if stripTop != "" {
			prefix := filepath.Clean(filepath.FromSlash(strings.TrimSuffix(stripTop, "/")))
			if entry == prefix {
				continue
			}
			// Archives may place files either at the root or inside a named
			// directory. Strip the wrapper only when the entry has that prefix.
			if strings.HasPrefix(entry, prefix+string(os.PathSeparator)) {
				entry = strings.TrimPrefix(strings.TrimPrefix(entry, prefix), string(os.PathSeparator))
			}
		}
		if entry == "." || entry == "" { continue }
		if extracted > 100000 { return fmt.Errorf("framework archive contains too many files") }
		target := filepath.Join(root, entry)
		rel, err := filepath.Rel(root, target)
		if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(os.PathSeparator)) || filepath.IsAbs(rel) {
			return fmt.Errorf("archive entry escapes project root: %q", file.Name)
		}
		if file.Mode()&os.ModeSymlink != 0 { return fmt.Errorf("archive contains an unexpected symbolic link: %q", file.Name) }
		if file.FileInfo().IsDir() {
			if err := os.MkdirAll(target, 0o755); err != nil { return err }
			continue
		}
		if !file.Mode().IsRegular() { return fmt.Errorf("archive contains a non-regular file: %q", file.Name) }
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil { return err }
		src, err := file.Open()
		if err != nil { return err }
		dst, err := os.OpenFile(target, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
		if err != nil { _ = src.Close(); return err }
		entryLimit := maxEntryUncompressed
		if remaining := maxTotalUncompressed - totalUncompressed; remaining < entryLimit {
			entryLimit = remaining
		}
		written, copyErr := io.Copy(dst, io.LimitReader(src, entryLimit+1))
		srcErr := src.Close()
		dstErr := dst.Close()
		if copyErr != nil { return copyErr }
		if written > entryLimit {
			if entryLimit < maxEntryUncompressed {
				return fmt.Errorf("framework archive exceeds the 1 GiB total extracted-size safety limit")
			}
			return fmt.Errorf("archive entry %q exceeds the 128 MiB safety limit", file.Name)
		}
		totalUncompressed += written
		if srcErr != nil { return srcErr }
		if dstErr != nil { return dstErr }
		extracted++
	}
	if extracted == 0 { return fmt.Errorf("framework archive did not contain any files") }
	if log != nil { log(fmt.Sprintf("Extracted %d framework files", extracted)) }
	return nil
}
